import { Composition, Folder } from "remotion";
import { VIDEO_FPS, VIDEO_HEIGHT, VIDEO_WIDTH } from "./config";
import { TimedVideoProps, timingMetadata } from "./lib/timing";
import {
  LIST_COMPREHENSION_ID,
  ListComprehension,
  ListComprehensionProps,
} from "./videos/list-comprehension/ListComprehension";
import {
  LINEAR_REGRESSION_ID,
  LinearRegression,
  LinearRegressionProps,
} from "./videos/linear-regression/LinearRegression";
import {
  GRADIENT_DESCENT_ID,
  GradientDescent,
  GradientDescentProps,
} from "./videos/gradient-descent/GradientDescent";
import { LOGISTIC_REGRESSION_ID, LogisticEpisode } from "./videos/logistic-regression/LogisticEpisode";
import { KNN_ID, KnnEpisode } from "./videos/knn/KnnEpisode";
import { DECISION_TREE_ID, TreeEpisode } from "./videos/decision-tree/TreeEpisode";

// Each video's duration and timing come from public/<video-id>/timing.json
// (generated by generate_audio.py).
/** Shown on every video; can be changed per render in Studio's props panel. */
const WATERMARK = "ML avec Youssef";

const defaults: TimedVideoProps = { showTikTokOverlay: true, watermark: WATERMARK, timing: null };

const format = { width: VIDEO_WIDTH, height: VIDEO_HEIGHT, fps: VIDEO_FPS, durationInFrames: 1 };

export const RemotionRoot: React.FC = () => {
  return (
    <>
      <Composition
        id="ListComprehension"
        component={ListComprehension}
        {...format}
        defaultProps={{ showTikTokOverlay: true, watermark: WATERMARK, timing: null } satisfies ListComprehensionProps}
        calculateMetadata={timingMetadata<ListComprehensionProps>(LIST_COMPREHENSION_ID)}
      />
      <Composition
        id="LinearRegression"
        component={LinearRegression}
        {...format}
        defaultProps={{ showTikTokOverlay: true, watermark: WATERMARK, timing: null } satisfies LinearRegressionProps}
        calculateMetadata={timingMetadata<LinearRegressionProps>(LINEAR_REGRESSION_ID)}
      />
      <Composition
        id="GradientDescent"
        component={GradientDescent}
        {...format}
        defaultProps={{ showTikTokOverlay: true, watermark: WATERMARK, timing: null } satisfies GradientDescentProps}
        calculateMetadata={timingMetadata<GradientDescentProps>(GRADIENT_DESCENT_ID)}
      />
      {/* Series "ML en 1 minute": one episode per day, each standalone. */}
      <Folder name="ML-en-1-minute">
        <Composition
          id="Ep1LogisticRegression"
          component={LogisticEpisode}
          {...format}
          defaultProps={defaults}
          calculateMetadata={timingMetadata<TimedVideoProps>(LOGISTIC_REGRESSION_ID)}
        />
        <Composition
          id="Ep2Knn"
          component={KnnEpisode}
          {...format}
          defaultProps={defaults}
          calculateMetadata={timingMetadata<TimedVideoProps>(KNN_ID)}
        />
        <Composition
          id="Ep3DecisionTree"
          component={TreeEpisode}
          {...format}
          defaultProps={defaults}
          calculateMetadata={timingMetadata<TimedVideoProps>(DECISION_TREE_ID)}
        />
      </Folder>
    </>
  );
};
