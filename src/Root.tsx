import { Composition } from "remotion";
import { VIDEO_FPS, VIDEO_HEIGHT, VIDEO_WIDTH } from "./config";
import { timingMetadata } from "./lib/timing";
import {
  LIST_COMPREHENSION_ID,
  ListComprehension,
  ListComprehensionProps,
} from "./videos/list-comprehension/ListComprehension";
import {
  LINEAR_REGRESSION_ID,
  LinearRegression,
  LinearRegressionProps,
} from "./videos/linear-regression/LinearRegression";
import {
  GRADIENT_DESCENT_ID,
  GradientDescent,
  GradientDescentProps,
} from "./videos/gradient-descent/GradientDescent";

// Each video's duration and timing come from public/<video-id>/timing.json
// (generated by generate_audio.py).
const format = { width: VIDEO_WIDTH, height: VIDEO_HEIGHT, fps: VIDEO_FPS, durationInFrames: 1 };

export const RemotionRoot: React.FC = () => {
  return (
    <>
      <Composition
        id="ListComprehension"
        component={ListComprehension}
        {...format}
        defaultProps={{ showTikTokOverlay: true, timing: null } satisfies ListComprehensionProps}
        calculateMetadata={timingMetadata<ListComprehensionProps>(LIST_COMPREHENSION_ID)}
      />
      <Composition
        id="LinearRegression"
        component={LinearRegression}
        {...format}
        defaultProps={{ showTikTokOverlay: true, timing: null } satisfies LinearRegressionProps}
        calculateMetadata={timingMetadata<LinearRegressionProps>(LINEAR_REGRESSION_ID)}
      />
      <Composition
        id="GradientDescent"
        component={GradientDescent}
        {...format}
        defaultProps={{ showTikTokOverlay: true, timing: null } satisfies GradientDescentProps}
        calculateMetadata={timingMetadata<GradientDescentProps>(GRADIENT_DESCENT_ID)}
      />
    </>
  );
};
